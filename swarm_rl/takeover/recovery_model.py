"""Fixed E0003 recovery-cost regressors; training-only fitted preprocessing."""
from copy import deepcopy
import time

import numpy as np
import torch
from torch import nn


def joint_features(observations):
    values = np.asarray(observations, dtype=np.float32)
    if values.shape[-2:] != (4, 41) or not np.isfinite(values).all():
        raise ValueError("Expected finite joint observations (..., 4, 41)")
    return values.reshape(*values.shape[:-2], 164)


def fit_normalizer(train_features):
    values = np.asarray(train_features, dtype=np.float64)
    if values.ndim != 2 or values.shape[1] != 164 or len(values) == 0:
        raise ValueError("Normalizer requires nonempty training features [N,164]")
    if not np.isfinite(values).all():
        raise ValueError("Nonfinite training features")
    mean = values.mean(axis=0).astype(np.float32)
    scale = values.std(axis=0).astype(np.float32)
    scale[scale < 1e-6] = 1.0
    return mean, scale


def geometry_features(observations):
    values = np.asarray(observations, dtype=np.float64)
    joint_features(values)
    slot_error = np.linalg.norm(values[..., 3:6], axis=-1).max(axis=-1)
    velocity_error = np.linalg.norm(values[..., :3] - values[..., 9:12],
                                    axis=-1).max(axis=-1)
    separation = np.stack([np.linalg.norm(values[..., start:start+3], axis=-1)
                           for start in (12, 19, 26)], axis=-1).min(axis=(-2, -1))
    return np.stack([np.ones_like(slot_error), slot_error, velocity_error,
                     1.0 / np.maximum(separation, 0.1)], axis=-1)


def fit_ridge(train_geometry, targets, l2=0.001):
    x = np.asarray(train_geometry, dtype=np.float64)
    y = np.asarray(targets, dtype=np.float64)
    if x.ndim != 2 or x.shape[1] != 4 or y.shape != (len(x),):
        raise ValueError("Expected geometry [N,4] and targets [N]")
    penalty = np.diag([0.0, l2, l2, l2])  # Intercept is not penalized.
    return np.linalg.solve(x.T @ x + penalty, x.T @ y)


class RecoveryCostModel(nn.Module):
    def __init__(self, mean=None, scale=None, hidden_sizes=(64, 64), horizon=10.0):
        super().__init__()
        if tuple(hidden_sizes) != (64, 64):
            raise ValueError("E0003 fixes two 64-unit hidden layers")
        self.horizon = float(horizon)
        self.register_buffer('mean', torch.as_tensor(
            np.zeros(164, dtype=np.float32) if mean is None else mean).float())
        self.register_buffer('scale', torch.as_tensor(
            np.ones(164, dtype=np.float32) if scale is None else scale).float())
        self.network = nn.Sequential(nn.Linear(164, 64), nn.ReLU(),
                                     nn.Linear(64, 64), nn.ReLU(), nn.Linear(64, 1))

    def forward(self, features):
        return self.horizon * torch.sigmoid(
            self.network((features - self.mean) / self.scale)).squeeze(-1)


def load_predictor(path, device='cpu'):
    # The checkpoint is an artifact generated by this experiment, not an external model.
    checkpoint = torch.load(path, map_location=device, weights_only=False)
    model = RecoveryCostModel(hidden_sizes=checkpoint['hidden_sizes'],
                              horizon=checkpoint['horizon']).to(device)
    model.load_state_dict(checkpoint['state_dict'])
    model.eval()
    return model, checkpoint


def predict(model, features):
    device = next(model.parameters()).device
    with torch.no_grad():
        return model(torch.as_tensor(features, dtype=torch.float32,
                                     device=device)).cpu().numpy()


def train_predictor(train_x, train_y, val_x, val_y, specification, checkpoint_path):
    """One fixed training run; validation selects an epoch, never preprocessing."""
    started = time.monotonic()
    seed = specification['torch_seed']
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    device = torch.device(specification['device'])
    if device.type == 'cuda' and not torch.cuda.is_available():
        raise RuntimeError('Configured CUDA device unavailable; no silent fallback')
    mean, scale = fit_normalizer(train_x)
    model = RecoveryCostModel(mean, scale, specification['hidden_sizes']).to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=specification['learning_rate'])
    tensors = [torch.as_tensor(value, dtype=torch.float32, device=device)
               for value in (train_x, train_y, val_x, val_y)]
    x, y, vx, vy = tensors
    generator = torch.Generator(device='cpu').manual_seed(seed)
    history, best_mse, best_epoch, best_state = [], float('inf'), None, None
    for epoch in range(1, specification['epochs'] + 1):
        model.train()
        permutation = torch.randperm(len(x), generator=generator)
        for indices in permutation.split(specification['batch_size']):
            indices = indices.to(device)
            optimizer.zero_grad(set_to_none=True)
            loss = ((model(x[indices]) - y[indices]) ** 2).mean()
            if not torch.isfinite(loss):
                raise RuntimeError(f'Nonfinite training loss at epoch {epoch}')
            loss.backward()
            optimizer.step()
        model.eval()
        with torch.no_grad():
            train_mse = float(((model(x) - y) ** 2).mean().item())
            val_mse = float(((model(vx) - vy) ** 2).mean().item())
        history.append({'epoch': epoch, 'training_mse': train_mse,
                        'validation_mse': val_mse})
        if not np.isfinite(val_mse):
            raise RuntimeError(f'Nonfinite validation loss at epoch {epoch}')
        if val_mse < best_mse:
            best_mse, best_epoch = val_mse, epoch
            best_state = {key: value.detach().cpu().clone()
                          for key, value in model.state_dict().items()}
    if best_state is None:
        raise RuntimeError('No trained checkpoint')
    model.load_state_dict(best_state)
    checkpoint = {'state_dict': best_state, 'hidden_sizes': [64, 64], 'horizon': 10.0,
                  'selected_epoch': best_epoch, 'selected_validation_mse': best_mse,
                  'specification': deepcopy(specification),
                  'normalizer_fit_split': 'training_only', 'feature_dim': 164}
    torch.save(checkpoint, checkpoint_path)
    reloaded, _ = load_predictor(checkpoint_path, device=str(device))
    before, after = predict(model, val_x), predict(reloaded, val_x)
    np.testing.assert_array_equal(before, after)
    return model, {'epoch_history': history, 'selected_epoch': best_epoch,
                   'selected_validation_mse': best_mse,
                   'checkpoint_reload_max_absolute_error': float(np.max(np.abs(before-after))),
                   'training_wall_seconds': time.monotonic() - started,
                   'seed': seed, 'device': str(device)}


def errors(targets, predictions):
    target, prediction = np.asarray(targets), np.asarray(predictions)
    if target.shape != prediction.shape or not np.isfinite(prediction).all():
        raise ValueError('Invalid predictions')
    if len(target) == 0:
        return {'count': 0, 'mae': None, 'rmse': None}
    error = prediction - target
    return {'count': len(target), 'mae': float(np.abs(error).mean()),
            'rmse': float(np.sqrt(np.square(error).mean()))}
